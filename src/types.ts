export type CategoryId = 'cigarettes' | 'joints' | 'cigars';

export const CATEGORY_IDS: readonly CategoryId[] = ['cigarettes', 'joints', 'cigars'] as const;

/** Which time horizon drives the pacing/status engine for a category. */
export type PacingFocus = 'daily' | 'weekly' | 'monthly';

/**
 * Penalty rule: for every unit over the monthly budget, deduct `perExcess`
 * units from next month's budget. Stored in settings, so it is the permanent
 * default for every month until changed.
 */
export interface PenaltyRule {
  perExcess: number;
}

export interface CategorySettings {
  monthlyLimit: number;
  /** null / 0 = no weekly limit */
  weeklyLimit: number | null;
  /** null = auto (effective monthly / days in month) */
  dailyOverride: number | null;
  focus: PacingFocus;
  penalty: PenaltyRule;
}

export interface LogEntry {
  id: string;
  category: CategoryId;
  /** epoch milliseconds */
  timestamp: number;
  /** epoch ms when the entry was created (used for undo order) */
  createdAt: number;
  note?: string;
}

/** monthKey ("YYYY-MM") → category → value */
export type MonthOverrides = Record<string, Partial<Record<CategoryId, number>>>;

export interface AppData {
  version: 2;
  settings: Record<CategoryId, CategorySettings>;
  logs: LogEntry[];
  /** Manual override of the penalty APPLIED to a month (i.e. generated by the previous month). */
  penaltyOverrides: MonthOverrides;
  /** Manual override of the base budget for a specific month. */
  baseBudgetOverrides: MonthOverrides;
}

/** exact = precisely on target (blue); warning = real caution (amber); bad = over budget (red) */
export type StatusLevel = 'good' | 'exact' | 'warning' | 'bad';

export type Page = 'dashboard' | 'history';
